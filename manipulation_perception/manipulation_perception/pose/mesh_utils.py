"""
Mesh file utilities shared by pose-estimation tools and workers.

Responsibility:
- Read OBJ vertices and estimate mesh dimensions.
- Write scaled or densified OBJ files.
- Copy OBJ material assets needed by backend datasets.

Does not own:
- ROS parameters or topics.
- Pose-estimation worker protocols.
- Dataset CLI argument parsing.
"""

from __future__ import annotations

import math
from pathlib import Path
import shutil

import numpy as np


def mesh_unit_scale_to_mm(mesh_units: str) -> float:
    """Return the multiplicative conversion from configured units to millimetres."""
    return 1000.0 if mesh_units in {"m", "meter", "meters"} else 1.0


def mesh_unit_scale_to_m(mesh_units: str) -> float:
    """Return the multiplicative conversion from configured units to metres."""
    return 0.001 if mesh_units in {"mm", "millimeter", "millimeters"} else 1.0


def read_obj_vertices(input_path: Path) -> np.ndarray:
    """Read OBJ vertex positions as an ``N x 3`` float64 array."""
    vertices: list[tuple[float, float, float]] = []
    for line in input_path.read_text(errors="ignore").splitlines():
        if not line.startswith("v "):
            continue
        parts = line.split()
        if len(parts) >= 4:
            vertices.append((float(parts[1]), float(parts[2]), float(parts[3])))
    if not vertices:
        raise ValueError(f"OBJ не содержит vertices: {input_path}")
    return np.asarray(vertices, dtype=np.float64)


def count_obj_vertices(input_path: Path) -> int:
    """Count geometric vertex records without parsing the rest of the OBJ."""
    return sum(
        1
        for line in input_path.read_text(errors="ignore").splitlines()
        if line.startswith("v ")
    )


def write_scaled_obj(input_path: Path, output_path: Path, scale: float) -> None:
    """Write an OBJ copy with only geometric vertex coordinates scaled."""
    lines = []
    for line in input_path.read_text(errors="ignore").splitlines():
        if line.startswith("v "):
            parts = line.split()
            if len(parts) >= 4:
                x, y, z = (
                    float(parts[1]) * scale,
                    float(parts[2]) * scale,
                    float(parts[3]) * scale,
                )
                suffix = " ".join(parts[4:])
                line = f"v {x:.9g} {y:.9g} {z:.9g}" + (f" {suffix}" if suffix else "")
        lines.append(line)
    output_path.write_text("\n".join(lines) + "\n")


def write_dense_scaled_obj(
    input_path: Path,
    output_path: Path,
    scale: float,
    min_vertices: int = 2500,
    fallback: str = "scaled",
) -> None:
    """
    Triangulate and subdivide an OBJ into a denser scaled mesh.

    Polygon faces are fan-triangulated and each triangle is independently
    subdivided until the approximate vertex target is met. Material-library
    declarations are retained, but normals/UVs are intentionally regenerated by
    downstream loaders. Meshes without usable faces follow ``fallback``.
    """
    vertices: list[tuple[float, float, float]] = []
    triangles: list[tuple[int, int, int]] = []
    mtllib_line = ""
    usemtl_line = ""

    for raw_line in input_path.read_text(errors="ignore").splitlines():
        line = raw_line.strip()
        if line.startswith("mtllib ") and not mtllib_line:
            mtllib_line = line
        elif line.startswith("usemtl ") and not usemtl_line:
            usemtl_line = line
        elif line.startswith("v "):
            parts = line.split()
            if len(parts) >= 4:
                vertices.append(
                    (
                        float(parts[1]) * scale,
                        float(parts[2]) * scale,
                        float(parts[3]) * scale,
                    )
                )
        elif line.startswith("f "):
            vertex_indices = []
            for token in line.split()[1:]:
                vertex_token = token.split("/", maxsplit=1)[0]
                if not vertex_token:
                    continue
                index = int(vertex_token)
                if index < 0:
                    index = len(vertices) + index + 1
                vertex_indices.append(index - 1)
            for offset in range(1, len(vertex_indices) - 1):
                triangles.append(
                    (
                        vertex_indices[0],
                        vertex_indices[offset],
                        vertex_indices[offset + 1],
                    )
                )

    if not vertices or not triangles:
        if fallback == "copy":
            shutil.copy2(input_path, output_path)
        else:
            write_scaled_obj(input_path, output_path, scale)
        return

    subdivision = max(
        1,
        math.ceil(
            math.sqrt((2.0 * float(min_vertices)) / float(len(triangles)))
        ),
    )
    dense_vertices: list[tuple[float, float, float]] = []
    dense_faces: list[tuple[int, int, int]] = []

    for triangle in triangles:
        tri_vertices = [vertices[index] for index in triangle]
        grid: dict[tuple[int, int], int] = {}

        for i in range(subdivision + 1):
            for j in range(subdivision + 1 - i):
                weight_b = float(i) / float(subdivision)
                weight_c = float(j) / float(subdivision)
                weight_a = 1.0 - weight_b - weight_c
                point = (
                    tri_vertices[0][0] * weight_a
                    + tri_vertices[1][0] * weight_b
                    + tri_vertices[2][0] * weight_c,
                    tri_vertices[0][1] * weight_a
                    + tri_vertices[1][1] * weight_b
                    + tri_vertices[2][1] * weight_c,
                    tri_vertices[0][2] * weight_a
                    + tri_vertices[1][2] * weight_b
                    + tri_vertices[2][2] * weight_c,
                )
                dense_vertices.append(point)
                grid[(i, j)] = len(dense_vertices)

        for i in range(subdivision):
            for j in range(subdivision - i):
                dense_faces.append((grid[(i, j)], grid[(i + 1, j)], grid[(i, j + 1)]))
                if j < subdivision - i - 1:
                    dense_faces.append((grid[(i + 1, j)], grid[(i + 1, j + 1)], grid[(i, j + 1)]))

    lines = []
    if mtllib_line:
        lines.append(mtllib_line)
    lines.append(f"o {input_path.stem}_dense")
    for vertex in dense_vertices:
        lines.append(f"v {vertex[0]:.9g} {vertex[1]:.9g} {vertex[2]:.9g}")
    if usemtl_line:
        lines.append(usemtl_line)
    for face in dense_faces:
        lines.append(f"f {face[0]} {face[1]} {face[2]}")
    output_path.write_text("\n".join(lines) + "\n")


def copy_material_assets(mesh_path: Path, target_dir: Path) -> None:
    """Copy directly referenced MTL files and their map textures beside an OBJ."""
    if mesh_path.suffix.lower() != ".obj":
        return

    referenced_files: set[Path] = set()
    for line in mesh_path.read_text(errors="ignore").splitlines():
        parts = line.strip().split(maxsplit=1)
        if len(parts) == 2 and parts[0] == "mtllib":
            referenced_files.add(mesh_path.parent / parts[1])

    for mtl_path in list(referenced_files):
        if not mtl_path.is_file():
            continue
        shutil.copy2(mtl_path, target_dir / mtl_path.name)
        for line in mtl_path.read_text(errors="ignore").splitlines():
            parts = line.strip().split(maxsplit=1)
            if len(parts) == 2 and parts[0].startswith("map_"):
                texture_path = mtl_path.parent / parts[1]
                if texture_path.is_file():
                    shutil.copy2(texture_path, target_dir / texture_path.name)


def obj_diameter_mm(mesh_path: Path, mesh_units: str) -> float:
    """Return the OBJ axis-aligned bounding-box diagonal in millimetres."""
    vertices = read_obj_vertices(mesh_path)
    vertices_mm = vertices * mesh_unit_scale_to_mm(mesh_units)
    extents = vertices_mm.max(axis=0) - vertices_mm.min(axis=0)
    return float(np.linalg.norm(extents))


def estimate_obj_size_m(mesh_path: Path, mesh_units: str) -> tuple[float, float, float]:
    """Return metric XYZ extents, using a 5 cm fallback for unreadable meshes."""
    if mesh_path.suffix.lower() != ".obj":
        return 0.05, 0.05, 0.05
    try:
        vertices = read_obj_vertices(mesh_path)
    except ValueError:
        return 0.05, 0.05, 0.05
    coords = vertices * mesh_unit_scale_to_m(mesh_units)
    extents = coords.max(axis=0) - coords.min(axis=0)
    return tuple(float(max(value, 0.001)) for value in extents)
